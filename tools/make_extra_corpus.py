def build(name: str, sections: list[tuple[str, list[str]]]) -> Path:
    out = OUT_DIR / f"{name}.pdf"
    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_font("simhei", "", FONT)
    pdf.add_page()

    pdf.set_font("simhei", size=20)
    pdf.multi_cell(0, 12, name)
    pdf.ln(2)
    pdf.set_font("simhei", size=10)
    pdf.multi_cell(0, 6, "内部资料 ｜ 版本 1.0")
    pdf.ln(4)

    for heading, paragraphs in sections:
        pdf.set_font("simhei", size=14)
        pdf.multi_cell(0, 9, heading)
        pdf.ln(1)
        pdf.set_font("simhei", size=11)
        for para in paragraphs:
            pdf.multi_cell(0, 7, para)
            pdf.ln(1)
        pdf.ln(2)

    pdf.output(str(out))
    return out


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, sections in DOCS.items():
        path = build(name, sections)
        print(f"saved: {path.name} ({path.stat().st_size / 1024:.0f} KB, {len(sections)} 节)")


if __name__ == "__main__":
    main()
